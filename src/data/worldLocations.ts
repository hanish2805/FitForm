export function resolveLocationForPosition(
  x: number,
  z: number,
  fallback: WorldLocationMeta['id'] = 'training_center',
): WorldLocationMeta['id'] {
  for (let i = 0; i < WORLD_LOCATIONS.length; i++) {
    const loc = WORLD_LOCATIONS[i];
    if (Math.hypot(x - loc.x, z - loc.z) <= loc.radius) {
      return loc.id;
    }
  }
  return fallback;
}

